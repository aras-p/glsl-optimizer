#!/usr/bin/env python3
"""Generate glsl-optimizer's minimal pipe_format support from an upstream Mesa
source tree:

  src/util/format/u_format_gen.h   enum pipe_format with only the formats that
                                   glsl-optimizer's sources mention
  src/util/format/u_format.h       format description types + the few helpers
                                   the compiler calls
  src/util/format/u_format_table.c descriptions of those formats

The compiler only needs formats that GLSL image layout qualifiers can name; the
upstream format machinery (450+ formats, pixel pack/unpack code, texture
codecs) is not needed. Needs PyYAML (upstream u_format_table.py reads YAML).

usage: upgrade-tools/gen_minimal_formats.py /path/to/mesa   (run from the repo root)
"""
import os
import re
import subprocess
import sys
import tempfile

mesa = os.path.abspath(sys.argv[1])
FMT = "src/util/format/"
# helpers from u_format.h that glsl-optimizer code calls (plus what they need)
HELPERS = ["util_format_short_name", "util_format_get_nr_components",
           "util_format_get_first_non_void_channel", "util_format_get_blocksizebits"]
TYPES = ["enum util_format_layout", "struct util_format_block", "enum util_format_type",
         "enum util_format_colorspace", "struct util_format_channel_description",
         "enum pipe_video_chroma_format", "struct util_format_description"]

# formats referenced by our sources (names only; values are not used anywhere)
used = set()
for root in ["src/compiler", "src/mesa", "src/gallium", "proto"]:
    for dp, dn, fn in os.walk(root):
        for f in fn:
            if f.endswith((".c", ".cpp", ".h", ".y", ".yy")) and f not in ("u_format_gen.h", "u_format_table.c"):
                used |= set(re.findall(r"\bPIPE_FORMAT_[A-Za-z0-9_]+\b", open(os.path.join(dp, f), errors="ignore").read()))
used.discard("PIPE_FORMAT_COUNT")
used.add("PIPE_FORMAT_NONE")

gen = os.path.join(mesa, FMT, "u_format_table.py")
yaml = os.path.join(mesa, FMT, "u_format.yaml")
enums = subprocess.run([sys.executable, gen, yaml, "--enums"], capture_output=True, text=True, check=True).stdout
table = subprocess.run([sys.executable, gen, yaml], capture_output=True, text=True, check=True).stdout
upstream_h = open(os.path.join(mesa, FMT, "u_format.h")).read()

def license_of(text):
    return text[:text.index("*/") + 2] + "\n"

NOTE = ("/*\n * glsl-optimizer change: minimal version, generated by "
        "upgrade-tools/gen_minimal_formats.py\n * from Mesa's %s. Only what the GLSL compiler uses.\n */\n")

# --- enum pipe_format
all_formats = re.findall(r"^\s+(PIPE_FORMAT_[A-Za-z0-9_]+)\s*(?:=\s*\d+\s*)?,", enums[enums.index("enum pipe_format {"):], re.M)
missing = used - set(all_formats)
assert not missing, missing
keep = [f for f in all_formats if f in used]
out = license_of(enums) + NOTE % "u_format.yaml" + '''
#ifndef U_FORMAT_GEN_H
#define U_FORMAT_GEN_H

#ifdef __cplusplus
extern "C" {
#endif

enum pipe_format {
''' + "".join("   %s,\n" % f for f in keep) + '''   PIPE_FORMAT_COUNT
};

#ifdef __cplusplus
}
#endif

#endif /* U_FORMAT_GEN_H */
'''
open(FMT + "u_format_gen.h", "w").write(out)

# --- u_format.h subset
def extract_type(decl):
    m = re.search(r"((?:/\*\*(?:(?!\*/).)*\*/\n)?" + re.escape(decl) + r"\s*\{.*?\n\};\n)", upstream_h, re.S)
    assert m, decl
    return m.group(1)

def extract_inline(name):
    m = re.search(r"((?:/\*\*(?:(?!\*/).)*\*/\n)?static inline [^\n]*\n" + re.escape(name) + r"\(.*?\n\}\n)", upstream_h, re.S)
    assert m, name
    return m.group(1)

parts = [license_of(upstream_h), NOTE % "util/format/u_format.h", '''
#ifndef U_FORMAT_H
#define U_FORMAT_H

#include <assert.h>
#include <stdbool.h>
#include "util/format/u_formats.h"
#include "util/macros.h"

#ifdef __cplusplus
extern "C" {
#endif

''']
for t in TYPES:
    parts.append(extract_type(t) + "\n")
parts.append('''const struct util_format_description *
util_format_description(enum pipe_format format) ATTRIBUTE_CONST;

''')
for h in HELPERS:
    parts.append(extract_inline(h) + "\n")
parts.append('''#ifdef __cplusplus
}
#endif

#endif /* U_FORMAT_H */
''')
open(FMT + "u_format.h", "w").write("".join(parts))

# --- description table
start = table.index("util_format_descriptions[PIPE_FORMAT_COUNT] = {")
body = table[start:table.index("\n};", start)]
# split at the start of each "   [PIPE_FORMAT_X] = {" entry
starts = [m.start() for m in re.finditer(r"^   \[PIPE_FORMAT_", body, re.M)]
entries = []
for a, b in zip(starts, starts[1:] + [len(body)]):
    text = body[a:b].rstrip() + "\n\n"
    entries.append((text, re.match(r"   \[(PIPE_FORMAT_[A-Za-z0-9_]+)\]", text).group(1)))
kept = []
for text, name in entries:
    if name not in used:
        continue
    # equivalents outside our subset do not exist here
    text = re.sub(r"(\.(?:srgb|linear)_equivalent = )(PIPE_FORMAT_[A-Za-z0-9_]+)",
                  lambda m: m.group(1) + (m.group(2) if m.group(2) in used else "PIPE_FORMAT_NONE"), text)
    kept.append(text)
out = license_of(table) + NOTE % "u_format.yaml (descriptions only)" + '''
#include "util/format/u_format.h"

static const struct util_format_description
util_format_descriptions[PIPE_FORMAT_COUNT] = {
''' + "".join(kept) + '''};

const struct util_format_description *
util_format_description(enum pipe_format format)
{
   assert(format >= 0 && format < PIPE_FORMAT_COUNT);
   return &util_format_descriptions[format];
}
'''
open(FMT + "u_format_table.c", "w").write(out)
print("formats:", len(keep), "of", len(all_formats))
