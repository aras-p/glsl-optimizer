#!/usr/bin/env python3
"""Generate src/compiler/nir/nir_glslopt_helpers.c: small helper functions
copied verbatim out of NIR files that glsl-optimizer does not build otherwise
(they are lowering passes we never run, but core NIR code calls a few of
their helpers). Re-run after a Mesa upgrade.

usage: upgrade-tools/extract_nir_helpers.py /path/to/mesa   (from the repo root)
"""
import os
import re
import sys

MESA_NIR = os.path.join(sys.argv[1], "src/compiler/nir/")
NIR = "src/compiler/nir/"
FUNCS = [
    ("nir_lower_io.c", "nir_is_arrayed_io"),
    ("nir_lower_io.c", "nir_get_io_offset_src_number"),
    ("nir_lower_io.c", "nir_get_io_offset_src"),
    ("nir_lower_io.c", "nir_get_io_uniform_offset_src_number"),
    ("nir_lower_io.c", "nir_get_io_uniform_offset_src"),
    ("nir_lower_io.c", "nir_is_input_load"),
    ("nir_lower_explicit_io.c", "nir_get_explicit_deref_align"),
    ("nir_lower_double_ops.c", "nir_lower_doubles_op_to_options_mask"),
    ("nir_lower_int64.c", "nir_lower_int64_op_to_options_mask"),
]
# macros the copied functions use, taken from the same files
MACROS = [("nir_lower_io.c", "IMG_CASE")]


def extract_function(src, name):
    # return type on the line before "name(", body until the first "}" in column 0
    m = re.search(r"\n([^\n]+)\n" + re.escape(name) + r"\(", src)
    assert m, name
    start = m.start(1)
    end = src.index("\n}\n", m.end()) + 3
    return src[start:end]


def extract_macro(src, name):
    m = re.search(r"^#define " + re.escape(name) + r"\b.*?(?<!\\)\n", src, re.M | re.S)
    assert m, name
    return m.group(0)


out = ['''/*
 * glsl-optimizer change: helpers copied verbatim from Mesa NIR files that are
 * otherwise not part of glsl-optimizer (lowering passes we never run). Core
 * NIR code (nir.c, nir_validate.c, nir_deref.c, nir_opt_constant_folding.c,
 * nir_opt_dce.c, nir_loop_analyze.c) calls these. Generated by
 * upgrade-tools/extract_nir_helpers.py; do not edit.
 *
 * Original copyright: see the files named below (MIT license).
 */

#include "nir.h"
#include "nir_builder.h"
#include "nir_deref.h"

''']
cache = {}
for f, name in MACROS:
    src = cache.setdefault(f, open(MESA_NIR + f).read())
    out.append("/* from %s */\n%s\n" % (f, extract_macro(src, name)))
for f, name in FUNCS:
    src = cache.setdefault(f, open(MESA_NIR + f).read())
    out.append("/* from %s */\n%s\n" % (f, extract_function(src, name)))
open(NIR + "nir_glslopt_helpers.c", "w").write("".join(out))
print("wrote", NIR + "nir_glslopt_helpers.c")
